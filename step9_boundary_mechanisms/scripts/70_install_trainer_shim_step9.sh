#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# step9_boundary_mechanisms/scripts/70_install_trainer_shim_step9.sh
#
#   Registers nnUNetTrainerSandwichBnd with the **zk** environment.
#
#   Same mechanism as step6_sandwich_squeeze/scripts/70_install_trainer_shim.sh:
#   zk ships nnunetv2 2.6.2, whose `-tr <Name>` lookup only iterates the FILES
#   inside <site-packages>/nnunetv2/training/nnUNetTrainer (no nnUNet_extTrainer
#   before 2.8).  The real implementation stays in step9/trainer; the generated
#   file only puts step9/trainer AND step6/trainer on sys.path and re-exports
#   the class, so BOTH training and inference (the predictor re-imports the
#   trainer named in the checkpoint) resolve it.
#
#   Idempotent.  Delete the generated file to unregister.
#
#   usage: bash scripts/70_install_trainer_shim_step9.sh
# ---------------------------------------------------------------------------
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."          # -> step9_boundary_mechanisms
STEP9_ROOT="$(pwd)"
USS_ROOT="$(cd "$STEP9_ROOT/.." && pwd)"
STEP6_TRAINER="$USS_ROOT/step6_sandwich_squeeze/trainer"

# reuse step6's env for the venv / dataset / fold definitions
# shellcheck source=/dev/null
source "$USS_ROOT/step6_sandwich_squeeze/scripts/env_step6.sh" > /dev/null

VENV="$STEP6_VENV"
TRAINER_DIR="$STEP9_ROOT/trainer"
SHIM_DIR="$("$VENV/bin/python" -c 'import os, nnunetv2; print(os.path.join(nnunetv2.__path__[0], "training", "nnUNetTrainer"))')"
TARGET="$SHIM_DIR/nnUNetTrainerStep9Bnd.py"

echo "[shim9] venv            = $VENV"
echo "[shim9] nnunetv2        = $("$VENV/bin/python" -c 'import nnunetv2; print(getattr(nnunetv2, "__version__", "unknown"))')"
echo "[shim9] target          = $TARGET"
echo "[shim9] re-exports from = $TRAINER_DIR (step9) + $STEP6_TRAINER (step6)"

cat > "$TARGET" <<PYEOF
#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
SHIM -- makes the step-9 BOUNDARY-METRIC fine-tune trainer discoverable by this
nnU-Net install.

GENERATED by step9_boundary_mechanisms/scripts/70_install_trainer_shim_step9.sh
Do not edit here; edit that script so the shim stays reproducible.

Carries no logic: puts the step-9 and step-6 trainer directories on sys.path and
re-exports the class.  Delete it to unregister.
"""
import sys

for _d in ("$TRAINER_DIR", "$STEP6_TRAINER"):
    if _d not in sys.path:
        sys.path.insert(0, _d)

from nnUNetTrainerSandwichBnd import nnUNetTrainerSandwichBnd  # noqa: E402,F401

__all__ = ["nnUNetTrainerSandwichBnd"]
PYEOF

echo "[shim9] verifying the registration the way nnU-Net resolves it ..."
"$VENV/bin/python" - <<'PYEOF'
import os
import sys

import torch
import nnunetv2
from nnunetv2.utilities.find_class_by_name import recursive_find_python_class

folder = os.path.join(nnunetv2.__path__[0], "training", "nnUNetTrainer")
name = "nnUNetTrainerSandwichBnd"
c = recursive_find_python_class(folder, name, 'nnunetv2.training.nnUNetTrainer')
print("[shim9] %s -> %s" % (name, c))
assert c is not None, "trainer did not resolve"

from nnUNetTrainerSandwichResencW25 import nnUNetTrainerSandwichResencW25
assert issubclass(c, nnUNetTrainerSandwichResencW25)

import boundary_losses
print("[shim9] boundary_losses -> %s" % boundary_losses.__file__)

# the residual-encoder network must build through this path and emit 6 channels
kw = {"n_stages": 4, "features_per_stage": [4, 8, 16, 32],
      "conv_op": "torch.nn.modules.conv.Conv2d",
      "kernel_sizes": [[3, 3]] * 4, "strides": [[1, 1]] + [[2, 2]] * 3,
      "n_conv_per_stage": [1, 1, 1, 1], "n_conv_per_stage_decoder": [1, 1, 1],
      "conv_bias": True, "norm_op": "torch.nn.modules.instancenorm.InstanceNorm2d",
      "norm_op_kwargs": {"eps": 1e-05, "affine": True},
      "dropout_op": None, "dropout_op_kwargs": None,
      "nonlin": "torch.nn.LeakyReLU", "nonlin_kwargs": {"inplace": True}}
net = c.build_network_architecture(
    "dynamic_network_architectures.architectures.unet.ResidualEncoderUNet",
    kw, ["conv_op", "norm_op", "dropout_op", "nonlin"], 1, 2,
    enable_deep_supervision=True)
net.set_forward_mode("all")
out = net(torch.zeros(1, 1, 64, 64))
print("[shim9] training forward ->", [tuple(o.shape) for o in out][:2])
assert isinstance(out, (list, tuple)) and out[0].shape[1] == 6, "not 6 channels"
net.set_forward_mode("base")
out2 = net(torch.zeros(1, 1, 64, 64))
assert tuple(out2.shape) == (1, 2, 64, 64), "base version did not collapse to 2"
print("[shim9] OK - trainer resolves, resenc net builds, 6->2 channel switch works")
PYEOF
