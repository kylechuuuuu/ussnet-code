#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# step4_our_new_model_resunet_boundary/scripts/53_install_trainer_shim.sh
#
#   Installs (or refreshes) the one-file shim that makes the step-4 trainers
#   discoverable by the **zk** environment.
#
#   WHY THIS IS NEEDED
#   ------------------
#   `~/anaconda3/envs/zk` ships nnunetv2 **2.6.2**.  Its
#   `run/run_training.py::get_trainer_from_args` resolves `-tr <Name>` ONLY via
#
#       recursive_find_python_class(
#           <site-packages>/nnunetv2/training/nnUNetTrainer, <Name>,
#           'nnunetv2.training.nnUNetTrainer')
#
#   which iterates the FILES in exactly that folder and returns the first module
#   that has an attribute of that name.  2.6.2 has **no `nnUNet_extTrainer`
#   support** (that arrived in nnU-Net >= 2.8) -- which is why the original
#   `env_step4.sh` assumption did not work, and why the first launch died with:
#
#       RuntimeError: Could not find requested nnunet trainer
#       nnUNetTrainerProstateFPBoundary in nnunetv2.training.nnUNetTrainer
#
#   The project already recorded this quirk in
#   `step1_nnunet_baseline/scripts/restart_nnunet_with_zk.sh`.
#
#   We do NOT want to fork nnU-Net or copy the trainers into site-packages (the
#   project must stay the single source of truth).  Instead this drops ONE
#   logic-free module into that folder which puts our `trainer/` directory on
#   `sys.path` and re-exports the trainer classes.  That makes the lookup
#   succeed for training AND for prediction (the predictor re-imports the
#   trainer named in the checkpoint).
#
#   The baseline we must beat (Dice 96.106) was trained with this same env, so
#   running our model under zk is also what keeps the comparison fair.
#
#   Deleting the generated file unregisters the trainers again.  This script is
#   idempotent.
#
#   usage: bash scripts/53_install_trainer_shim.sh
# ---------------------------------------------------------------------------
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
source scripts/env_step4.sh

SHIM_DIR="$("$STEP4_VENV/bin/python" -c 'import os, nnunetv2; print(os.path.join(nnunetv2.__path__[0], "training", "nnUNetTrainer"))')"
TARGET="$SHIM_DIR/nnUNetTrainerStep4Fingerprint.py"
TRAINER_DIR="$STEP4_ROOT/trainer"

echo "[shim] venv            = $STEP4_VENV"
echo "[shim] nnunetv2        = $("$STEP4_VENV/bin/python" -c 'import nnunetv2; print(nnunetv2.__version__)')"
echo "[shim] target          = $TARGET"
echo "[shim] re-exports from = $TRAINER_DIR"

cat > "$TARGET" <<PYEOF
#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
SHIM -- makes the step4 fingerprint-driven trainers discoverable by THIS
nnU-Net install.

GENERATED by
  step4_our_new_model_resunet_boundary/scripts/53_install_trainer_shim.sh
Do not edit here; edit that script so the shim stays reproducible.

Why it exists
-------------
\`~/anaconda3/envs/zk\` ships nnunetv2 **2.6.2**.  Its
\`run/run_training.py::get_trainer_from_args\` resolves a trainer only through
\`recursive_find_python_class(<site-packages>/nnunetv2/training/nnUNetTrainer, ...)\`,
which scans *files in that folder*.  Unlike nnU-Net >= 2.8 it has no
\`nnUNet_extTrainer\` support, so a trainer living outside the package cannot be
registered.  (The project already hit this: see
\`step1_nnunet_baseline/scripts/restart_nnunet_with_zk.sh\`.)

The real implementations stay in the project, which remains the single source of
truth:

    $TRAINER_DIR

This file carries no logic.  It only puts that directory on sys.path and
re-exports the trainer classes, so that \`get_trainer_from_args\` (training) and
the predictor (inference, which re-imports the trainer named in the checkpoint)
both find them by class name.

Delete this file to unregister the trainers from this environment.
"""
import sys

_TRAINER_DIR = ("$TRAINER_DIR")
if _TRAINER_DIR not in sys.path:
    sys.path.insert(0, _TRAINER_DIR)

from nnUNetTrainerProstateFPBoundary import (            # noqa: E402,F401
    nnUNetTrainerProstateFPBoundary)
from nnUNetTrainerProstateResUNetFPBoundary import (     # noqa: E402,F401
    nnUNetTrainerProstateResUNetFPBoundary)
from nnUNetTrainerProstateFPPreEnc import (              # noqa: E402,F401
    nnUNetTrainerProstateFPPreEnc)
from nnUNetTrainerProstateFPPreEncR34 import (           # noqa: E402,F401
    nnUNetTrainerProstateFPPreEncR34)
from nnUNetTrainerProstateFPZone3 import (               # noqa: E402,F401
    nnUNetTrainerProstateFPZone3)

__all__ = ["nnUNetTrainerProstateFPBoundary",
           "nnUNetTrainerProstateResUNetFPBoundary",
           "nnUNetTrainerProstateFPPreEnc",
           "nnUNetTrainerProstateFPPreEncR34",
           "nnUNetTrainerProstateFPZone3"]
PYEOF

# ---- verify BOTH the training path and the prediction path ----------------
"$STEP4_VENV/bin/python" - <<'PYEOF'
import os, sys, nnunetv2
sys.path.insert(0, os.environ.get("PYTHONPATH", "").split(":")[0])
from nnunetv2.utilities.find_class_by_name import recursive_find_python_class
folder = os.path.join(nnunetv2.__path__[0], "training", "nnUNetTrainer")
want = ["nnUNetTrainerProstateFPBoundary",
        "nnUNetTrainerProstateResUNetFPBoundary",
        "nnUNetTrainerProstateFPPreEnc",
        "nnUNetTrainerProstateFPPreEncR34",
        "nnUNetTrainerProstateFPZone3"]
bad = []
for n in want:
    c = recursive_find_python_class(folder, n, "nnunetv2.training.nnUNetTrainer")
    print("[shim] %-38s -> %s" % (n, c))
    if c is None:
        bad.append(n)
if bad:
    print("[shim] FAILED to register: %s" % bad)
    sys.exit(1)
print("[shim] OK - all trainers resolve for training and for prediction")
PYEOF
