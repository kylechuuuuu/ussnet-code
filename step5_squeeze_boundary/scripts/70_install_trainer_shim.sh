#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# step5_squeeze_boundary/scripts/70_install_trainer_shim.sh
#
#   Registers the step-5 squeeze trainers with the **zk** environment.
#
#   WHY: `~/anaconda3/envs/zk` ships nnunetv2 **2.6.2**.  Its
#   `run/run_training.py::get_trainer_from_args` resolves `-tr <Name>` ONLY via
#       recursive_find_python_class(
#           <site-packages>/nnunetv2/training/nnUNetTrainer, <Name>,
#           'nnunetv2.training.nnUNetTrainer')
#   which iterates the FILES in exactly that folder.  2.6.2 has no
#   `nnUNet_extTrainer` support (that arrived in nnU-Net >= 2.8).  The project
#   already hit this in step 1 and solved it the same way in step 4
#   (scripts/53_install_trainer_shim.sh, whose mechanism this copies).
#
#   The real implementations stay in step5/trainer (single source of truth);
#   the generated file in site-packages only puts that directory on sys.path and
#   re-exports the classes, so BOTH training (`-tr Name`) and inference (the
#   predictor re-imports the trainer named in the checkpoint) resolve them.
#
#   Is is idempotent.  Delete the generated file to unregister.
#
#   usage: bash scripts/70_install_trainer_shim.sh
# ---------------------------------------------------------------------------
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
source scripts/env_step5.sh

SHIM_DIR="$("$STEP5_VENV/bin/python" -c 'import os, nnunetv2; print(os.path.join(nnunetv2.__path__[0], "training", "nnUNetTrainer"))')"
TARGET="$SHIM_DIR/nnUNetTrainerStep5Squeeze.py"
TRAINER_DIR="$STEP5_ROOT/trainer"

echo "[shim] venv            = $STEP5_VENV"
echo "[shim] nnunetv2        = $("$STEP5_VENV/bin/python" -c 'import nnunetv2; print(nnunetv2.__version__)')"
echo "[shim] target          = $TARGET"
echo "[shim] re-exports from = $TRAINER_DIR"

cat > "$TARGET" <<PYEOF
#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
SHIM -- makes the step-5 SQUEEZE (夹逼定理) trainers discoverable by this
nnU-Net install.

GENERATED by step5_squeeze_boundary/scripts/70_install_trainer_shim.sh
Do not edit here; edit that script so the shim stays reproducible.

Why it exists: zk's nnunetv2 2.6.2 resolves a trainer only by scanning the files
inside <site-packages>/nnunetv2/training/nnUNetTrainer (no nnUNet_extTrainer
support before 2.8).  The real implementations stay in the project:

    $TRAINER_DIR

This file carries no logic; it puts that directory on sys.path and re-exports
the classes.  Delete it to unregister.
"""
import sys

_TRAINER_DIR = ("$TRAINER_DIR")
if _TRAINER_DIR not in sys.path:
    sys.path.insert(0, _TRAINER_DIR)

from nnUNetTrainerProstateSqueeze import nnUNetTrainerProstateSqueeze        # noqa: E402,F401
from nnUNetTrainerProstateSqueezeIso import nnUNetTrainerProstateSqueezeIso  # noqa: E402,F401
from nnUNetTrainerProstateStock200 import nnUNetTrainerProstateStock200      # noqa: E402,F401

__all__ = ["nnUNetTrainerProstateSqueeze", "nnUNetTrainerProstateSqueezeIso",
           "nnUNetTrainerProstateStock200"]
PYEOF

echo "[shim] verifying the registration the way nnU-Net resolves it ..."
"$STEP5_VENV/bin/python" - <<'PYEOF'
import os, sys
import nnunetv2
from nnunetv2.utilities.find_class_by_name import recursive_find_python_class

folder = os.path.join(nnunetv2.__path__[0], "training", "nnUNetTrainer")
want = ["nnUNetTrainerProstateSqueeze", "nnUNetTrainerProstateSqueezeIso",
        "nnUNetTrainerProstateStock200"]
bad = []
for n in want:
    c = recursive_find_python_class(folder, n, 'nnunetv2.training.nnUNetTrainer')
    print("[shim] %-36s -> %s" % (n, c))
    if c is None:
        bad.append(n)
if bad:
    print("[shim] FAILED to register: %s" % bad)
    sys.exit(1)

# the 3-head network must also be constructible through the registration path
from nnunetv2.utilities.get_network_from_plans import get_network_from_plans
folder5 = os.environ["STEP5_ROOT"] if "STEP5_ROOT" in os.environ else None
sys.path.insert(0, os.path.join(folder5, "trainer")) if folder5 else None
from nnUNetTrainerProstateSqueeze import nnUNetTrainerProstateSqueeze
import torch
net = nnUNetTrainerProstateSqueeze.build_network_architecture(
    "dynamic_network_architectures.architectures.unet.PlainConvUNet",
    {"n_stages": 4, "features_per_stage": [4, 8, 16, 32],
     "conv_op": "torch.nn.modules.conv.Conv2d",
     "kernel_sizes": [[3, 3]] * 4, "strides": [[1, 1]] + [[2, 2]] * 3,
     "n_conv_per_stage": [1, 1, 1, 1], "n_conv_per_stage_decoder": [1, 1, 1],
     "conv_bias": True, "norm_op": "torch.nn.modules.instancenorm.InstanceNorm2d",
     "norm_op_kwargs": {"eps": 1e-05, "affine": True},
     "dropout_op": None, "dropout_op_kwargs": None,
     "nonlin": "torch.nn.LeakyReLU", "nonlin_kwargs": {"inplace": True}},
    ["conv_op", "norm_op", "dropout_op", "nonlin"], 1, 2, enable_deep_supervision=True)
out = net(torch.zeros(1, 1, 64, 64))
print("[shim] smoke forward ->", [tuple(o.shape) for o in out] if isinstance(out, (list, tuple)) else tuple(out.shape))
assert isinstance(out, (list, tuple)) and out[0].shape[1] == 6, "the 3-head output is not 6 channels"
print("[shim] OK - trainers resolve and the 3-head network builds")
PYEOF
